import AppKit
import Combine

/// Retention duration policy for clipboard items.
public enum ClipboardRetentionPolicy: String, CaseIterable, Sendable, Codable {
    case off = "Off"
    case oneHour = "1 Hour"
    case twentyFourHours = "24 Hours"
    case sevenDays = "7 Days"

    public var timeInterval: TimeInterval? {
        switch self {
        case .off: return nil
        case .oneHour: return 3600
        case .twentyFourHours: return 86400
        case .sevenDays: return 604800
        }
    }
}

/// Main-actor coordinator managing secure clipboard history, concealed password exclusions, and memory limits.
@MainActor
public final class ClipboardManager: ObservableObject {
    public static let shared = ClipboardManager()

    /// Well-known pasteboard types marking sensitive data that must never be recorded.
    nonisolated public static let concealedPasteboardTypes: [NSPasteboard.PasteboardType] = [
        NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"),
        NSPasteboard.PasteboardType("com.agilebits.onepassword"),
        NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
        NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"),
        NSPasteboard.PasteboardType("de.blinkd.openvpn")
    ]

    @Published public var retentionPolicy: ClipboardRetentionPolicy = .twentyFourHours {
        didSet {
            pruneExpiredItems()
        }
    }
    @Published public private(set) var items: [ClipboardItem] = []
    @Published public var searchQuery: String = ""

    public let maxItems: Int = 50
    private var lastChangeCount: Int = -1
    private var pollTimer: Timer?

    public init() {
        startMonitoring()
    }

    /// Pure check verifying if pasteboard contains sensitive or password manager metadata.
    nonisolated public static func isConcealed(types: [NSPasteboard.PasteboardType]) -> Bool {
        for concealed in concealedPasteboardTypes {
            if types.contains(concealed) {
                return true
            }
        }
        return false
    }

    /// Ingest a custom item directly (used for restores or testing).
    public func ingestItem(_ item: ClipboardItem) {
        guard retentionPolicy != .off else { return }
        prependAndClamp(item)
    }

    /// Ingest a text snippet into history, enforcing security concealment and deduplication.
    @discardableResult
    public func ingest(
        text: String,
        sourceApp: String? = nil,
        types: [NSPasteboard.PasteboardType] = []
    ) -> Bool {
        guard retentionPolicy != .off else { return false }
        guard !Self.isConcealed(types: types) else { return false }

        let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !trimmed.isEmpty else { return false }

        // Suppress identical consecutive copy
        if let top = items.first, top.type == .text, top.text == trimmed {
            return false
        }

        let item = ClipboardItem(
            type: .text,
            text: trimmed,
            byteSize: trimmed.utf8.count,
            sourceApp: sourceApp
        )

        prependAndClamp(item)
        return true
    }

    /// Ingest an image into history, enforcing security concealment.
    @discardableResult
    public func ingest(
        imageDimensions: CGSize,
        byteSize: Int,
        sourceApp: String? = nil,
        types: [NSPasteboard.PasteboardType] = []
    ) -> Bool {
        guard retentionPolicy != .off else { return false }
        guard !Self.isConcealed(types: types) else { return false }

        let item = ClipboardItem(
            type: .image,
            imageDimensions: imageDimensions,
            byteSize: byteSize,
            sourceApp: sourceApp
        )

        prependAndClamp(item)
        return true
    }

    /// Ingest file URLs into history, enforcing security concealment.
    @discardableResult
    public func ingest(
        filePaths: [String],
        sourceApp: String? = nil,
        types: [NSPasteboard.PasteboardType] = []
    ) -> Bool {
        guard retentionPolicy != .off else { return false }
        guard !Self.isConcealed(types: types) else { return false }
        guard !filePaths.isEmpty else { return false }

        let item = ClipboardItem(
            type: .fileURLs,
            filePaths: filePaths,
            sourceApp: sourceApp
        )

        prependAndClamp(item)
        return true
    }

    /// Inspect system pasteboard for changes.
    public func checkPasteboard() {
        let pasteboard = NSPasteboard.general
        let count = pasteboard.changeCount
        guard count != lastChangeCount else { return }
        lastChangeCount = count

        guard let types = pasteboard.types else { return }
        guard !Self.isConcealed(types: types) else { return }

        // Check for text
        if let str = pasteboard.string(forType: .string) {
            ingest(text: str, types: types)
        }
    }

    /// Return items filtered by search query and pruned by retention policy.
    public func filteredItems() -> [ClipboardItem] {
        pruneExpiredItems()
        let query = searchQuery.trimmingCharacters(in: .whitespacesAndNewlines).lowercased()
        guard !query.isEmpty else { return items }

        return items.filter { item in
            if let t = item.text, t.lowercased().contains(query) {
                return true
            }
            if let files = item.filePaths, files.contains(where: { $0.lowercased().contains(query) }) {
                return true
            }
            if item.previewText.lowercased().contains(query) {
                return true
            }
            return false
        }
    }

    /// Copy selected item back to macOS pasteboard.
    public func copyToPasteboard(item: ClipboardItem) {
        let pb = NSPasteboard.general
        pb.clearContents()

        switch item.type {
        case .text:
            if let t = item.text {
                pb.setString(t, forType: .string)
            }
        case .fileURLs:
            if let files = item.filePaths {
                let urls = files.map { URL(fileURLWithPath: $0) as NSURL }
                pb.writeObjects(urls)
            }
        case .image:
            break
        }

        // Update change count to prevent re-ingesting own copy
        self.lastChangeCount = pb.changeCount
    }

    /// Delete item from history.
    public func deleteItem(id: UUID) {
        items.removeAll { $0.id == id }
    }

    /// Clear all stored clipboard history.
    public func clearHistory() {
        items.removeAll()
    }

    /// Prune items exceeding the retention duration.
    public func pruneExpiredItems() {
        guard let interval = retentionPolicy.timeInterval else {
            if retentionPolicy == .off {
                items.removeAll()
            }
            return
        }

        let threshold = Date().addingTimeInterval(-interval)
        items.removeAll { $0.timestamp < threshold }
    }

    private func prependAndClamp(_ item: ClipboardItem) {
        items.insert(item, at: 0)
        if items.count > maxItems {
            items.removeLast(items.count - maxItems)
        }
    }

    private func startMonitoring() {
        pollTimer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { [weak self] _ in
            Task { @MainActor in
                self?.checkPasteboard()
            }
        }
    }

    deinit {
        pollTimer?.invalidate()
    }
}
