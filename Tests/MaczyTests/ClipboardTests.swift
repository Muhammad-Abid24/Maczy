import XCTest
import AppKit
@testable import MaczyKit

final class ClipboardTests: XCTestCase {

    func testConcealedTypesExcluded() {
        // Standard macOS password concealment
        let concealed1 = [NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType")]
        XCTAssertTrue(ClipboardManager.isConcealed(types: concealed1))

        // 1Password specific marker
        let onepass = [NSPasteboard.PasteboardType("com.agilebits.onepassword")]
        XCTAssertTrue(ClipboardManager.isConcealed(types: onepass))

        // Transient copy
        let transient = [NSPasteboard.PasteboardType("org.nspasteboard.TransientType")]
        XCTAssertTrue(ClipboardManager.isConcealed(types: transient))

        // Auto-generated tokens
        let autoGen = [NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")]
        XCTAssertTrue(ClipboardManager.isConcealed(types: autoGen))

        // Standard string
        let plain = [NSPasteboard.PasteboardType.string]
        XCTAssertFalse(ClipboardManager.isConcealed(types: plain))
    }

    @MainActor
    func testIngestConcealedTextRejected() {
        let manager = ClipboardManager()
        manager.clearHistory()

        let passwordTypes = [
            NSPasteboard.PasteboardType.string,
            NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType")
        ]

        let accepted = manager.ingest(text: "MasterPassword$4921", types: passwordTypes)
        XCTAssertFalse(accepted)
        XCTAssertTrue(manager.items.isEmpty)
    }

    @MainActor
    func testIngestNormalTextAndDeduplication() {
        let manager = ClipboardManager()
        manager.clearHistory()

        let ok1 = manager.ingest(text: "Hello Maczy")
        XCTAssertTrue(ok1)
        XCTAssertEqual(manager.items.count, 1)
        XCTAssertEqual(manager.items.first?.text, "Hello Maczy")

        // Duplicate adjacent copy should be suppressed
        let okDuplicate = manager.ingest(text: "Hello Maczy")
        XCTAssertFalse(okDuplicate)
        XCTAssertEqual(manager.items.count, 1)

        // Different copy
        let ok2 = manager.ingest(text: "Second Snippet")
        XCTAssertTrue(ok2)
        XCTAssertEqual(manager.items.count, 2)
        XCTAssertEqual(manager.items.first?.text, "Second Snippet")
    }

    @MainActor
    func testFIFOMaxCapacityEviction() {
        let manager = ClipboardManager()
        manager.clearHistory()

        // Insert 60 distinct items (limit is 50)
        for i in 1...60 {
            manager.ingest(text: "Snippet #\(i)")
        }

        XCTAssertEqual(manager.items.count, 50)
        // Top should be Snippet #60
        XCTAssertEqual(manager.items.first?.text, "Snippet #60")
        // Oldest preserved should be Snippet #11 (1...10 evicted)
        XCTAssertEqual(manager.items.last?.text, "Snippet #11")
    }

    @MainActor
    func testSearchFilter() {
        let manager = ClipboardManager()
        manager.clearHistory()

        manager.ingest(text: "Swift native programming")
        manager.ingest(text: "Rust memory safety guarantees")
        manager.ingest(text: "Python automation scripts")

        manager.searchQuery = "Rust"
        let rustResults = manager.filteredItems()
        XCTAssertEqual(rustResults.count, 1)
        XCTAssertEqual(rustResults.first?.text, "Rust memory safety guarantees")

        manager.searchQuery = "scripts"
        let scriptResults = manager.filteredItems()
        XCTAssertEqual(scriptResults.count, 1)
        XCTAssertEqual(scriptResults.first?.text, "Python automation scripts")

        manager.searchQuery = ""
        let allResults = manager.filteredItems()
        XCTAssertEqual(allResults.count, 3)
    }

    @MainActor
    func testRetentionPolicyExpiration() {
        let manager = ClipboardManager()
        manager.clearHistory()
        manager.retentionPolicy = .oneHour

        let freshItem = ClipboardItem(type: .text, text: "Fresh", timestamp: Date())
        let staleItem = ClipboardItem(type: .text, text: "Stale", timestamp: Date().addingTimeInterval(-7200)) // 2 hours ago

        manager.ingestItem(freshItem)
        manager.ingestItem(staleItem)
        XCTAssertEqual(manager.items.count, 2)

        // When retention is 1 hour, stale item (2 hours old) is pruned
        manager.pruneExpiredItems()
        XCTAssertEqual(manager.items.count, 1)
        XCTAssertEqual(manager.items.first?.text, "Fresh")

        // Off policy clears all
        manager.retentionPolicy = .off
        manager.pruneExpiredItems()
        XCTAssertEqual(manager.items.count, 0)
    }

    @MainActor
    func testDeleteAndClearHistory() {
        let manager = ClipboardManager()
        manager.clearHistory()

        manager.ingest(text: "Item To Keep")
        manager.ingest(text: "Item To Delete")
        XCTAssertEqual(manager.items.count, 2)

        if let toDelete = manager.items.first(where: { $0.text == "Item To Delete" }) {
            manager.deleteItem(id: toDelete.id)
        }
        XCTAssertEqual(manager.items.count, 1)
        XCTAssertEqual(manager.items.first?.text, "Item To Keep")

        manager.clearHistory()
        XCTAssertTrue(manager.items.isEmpty)
    }

    func testClipboardItemPreviewFormatting() {
        // Long text truncation
        let longText = String(repeating: "A", count: 100)
        let itemLong = ClipboardItem(type: .text, text: longText)
        XCTAssertTrue(itemLong.previewText.hasSuffix("…"))
        XCTAssertLessThanOrEqual(itemLong.previewText.count, 70)

        // Image dimensions
        let itemImage = ClipboardItem(type: .image, imageDimensions: CGSize(width: 800, height: 600))
        XCTAssertEqual(itemImage.previewText, "Image (800×600 pt)")
        XCTAssertEqual(itemImage.iconName, "photo")

        // File URLs
        let itemFiles = ClipboardItem(type: .fileURLs, filePaths: ["/tmp/document.pdf", "/tmp/photo.jpg"])
        XCTAssertTrue(itemFiles.previewText.contains("2 files"))
        XCTAssertEqual(itemFiles.iconName, "folder")
    }
}
